def get_position_by_device(device_id: int) -> dict | None:
    """查詢指定設備的車格資料"""
    url = f"{BASE_URL}/api/position/device/{device_id}"
    try:
        resp = requests.get(url, auth=AUTH, timeout=TIMEOUT)
        if resp.status_code == 200:
            return resp.json()
        print(f"  [WARN] device {device_id} → HTTP {resp.status_code}: {resp.text[:100]}")
        return None
    except Exception as e:
        print(f"  [ERROR] device {device_id}: {e}")
        return None


def update_position_org_district(position_id: str, org_id: str, district_id: str) -> bool:
    """更新車格的組織與場域"""
    url = f"{BASE_URL}/api/position/{position_id}"
    payload = {
        "organizationId": org_id,
        "districtId": district_id,
    }
    try:
        # 先嘗試 PATCH
        resp = requests.patch(url, auth=AUTH, headers=HEADERS, json=payload, timeout=TIMEOUT)
        if resp.status_code in (200, 204):
            return True
        # fallback: PUT
        resp = requests.put(url, auth=AUTH, headers=HEADERS, json=payload, timeout=TIMEOUT)
        if resp.status_code in (200, 204):
            return True
        print(f"  [FAIL] position {position_id} → HTTP {resp.status_code}: {resp.text[:150]}")
        return False
    except Exception as e:
        print(f"  [ERROR] position {position_id}: {e}")
        return False


def main():
    print("=" * 60)
    print("地磁設備批次設定組織/場域")
    print(f"目標：國雲科技 台南永康區（參照設備 {REF_DEVICE_ID}）")
    print("=" * 60)

    # Step 1：查詢參照設備 86350 取得 organizationId / districtId
    print(f"\n[Step 1] 查詢參照設備 {REF_DEVICE_ID} ...")
    ref_pos = get_position_by_device(REF_DEVICE_ID)
    if not ref_pos:
        print(f"ERROR: 無法取得設備 {REF_DEVICE_ID} 的資料，請確認 API 是否正常。")
        sys.exit(1)

    print(f"  參照設備資料：{json.dumps(ref_pos, ensure_ascii=False, indent=2)}")

    org_id = ref_pos.get("organizationId")
    district_id = ref_pos.get("districtId")

    if not org_id or not district_id:
        print("ERROR: 參照設備缺少 organizationId 或 districtId，請確認欄位名稱。")
        print("  回傳的欄位：", list(ref_pos.keys()))
        sys.exit(1)

    print(f"\n  目標 organizationId = {org_id}")
    print(f"  目標 districtId     = {district_id}")

    # Step 2：批次更新所有設備
    print(f"\n[Step 2] 開始批次更新 {len(DEVICE_IDS)} 台設備 ...")
    ok_count = 0
    skip_count = 0   # 查不到車格
    fail_count = 0
    already_count = 0
    errors = []

    for i, device_id in enumerate(DEVICE_IDS, 1):
        if i % 50 == 0 or i == 1:
            print(f"  進度：{i}/{len(DEVICE_IDS)} ...")

        pos = get_position_by_device(device_id)
        if not pos:
            skip_count += 1
            errors.append({"device": device_id, "reason": "查不到車格"})
            continue

        pos_id = pos.get("id")
        if not pos_id:
            skip_count += 1
            errors.append({"device": device_id, "reason": "車格無 id 欄位"})
            continue

        # 已經是目標值則跳過
        if pos.get("organizationId") == org_id and pos.get("districtId") == district_id:
            already_count += 1
            continue

        success = update_position_org_district(pos_id, org_id, district_id)
        if success:
            ok_count += 1
        else:
            fail_count += 1
            errors.append({"device": device_id, "positionId": pos_id, "reason": "更新失敗"})

        time.sleep(0.05)  # 避免打爆 API

    # Step 3：結果摘要
    print("\n" + "=" * 60)
    print("執行結果摘要")
    print("=" * 60)
    print(f"  ✅ 更新成功：{ok_count} 台")
    print(f"  ⏭  已是目標值（跳過）：{already_count} 台")
    print(f"  ⚠️  查不到車格：{skip_count} 台")
    print(f"  ❌ 更新失敗：{fail_count} 台")

    if errors:
        print("\n異常清單（前 20 筆）：")
        for e in errors[:20]:
            print(f"  {e}")

        # 輸出完整異常到檔案
        with open("/tmp/set_org_district_errors.json", "w", encoding="utf-8") as f:
            json.dump(errors, f, ensure_ascii=False, indent=2)
        print(f"\n完整異常清單已輸出至 /tmp/set_org_district_errors.json")


if __name__ == "__main__":
    main()
